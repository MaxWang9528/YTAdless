// ScriptConfig: names shared with bridge.js, and the generated config prelude (PLAN.md §5.1,
// §5.2). Owner: P0 (frozen contract).
//
// The prelude is the only JS source native code generates. Its one data slot is a JSON object
// written by `jsonString`, which mirrors `JSON.stringify` exactly, so the Node harness's
// generator produces identical text. `TestVectors/prelude.json` pins both.

import Foundation

public enum ScriptConfig {
    /// `window.__ytadless`; the same constant is `NS` in bridge.js.
    public static let namespace = "__ytadless"
    /// `webkit.messageHandlers.ytadless`; the same constant is `HANDLER` in bridge.js.
    public static let messageHandlerName = "ytadless"

    /// `{"build":…,"debug":…,"role":…}`, keys sorted, formatted like `JSON.stringify`.
    public static func configJSON(role: WebRole, debug: Bool, build: String) -> String {
        "{\"build\":\(jsonString(build)),\"debug\":\(debug),\"role\":\(jsonString(role.rawValue))}"
    }

    /// Defines a placeholder `window.__ytadless = {config}` that bridge.js replaces with the
    /// frozen runtime namespace. Does nothing if the namespace already exists.
    public static func prelude(role: WebRole, debug: Bool, build: String) -> String {
        let ns = jsonString(namespace)
        return """
        /* ytadless config prelude: generated by ScriptConfig.prelude (YTCore); read by bridge.js. */
        (() => { try { if (!Object.prototype.hasOwnProperty.call(window, \(ns))) Object.defineProperty(window, \(ns), { value: { config: Object.freeze(\(configJSON(role: role, debug: debug, build: build))) }, configurable: true, enumerable: false, writable: false }); } catch (e) {} })();

        """
    }

    /// A JSON string literal, byte-for-byte what `JSON.stringify(string)` returns.
    public static func jsonString(_ string: String) -> String {
        var out = "\""
        for scalar in string.unicodeScalars {
            switch scalar {
            case "\"": out += "\\\""
            case "\\": out += "\\\\"
            case "\u{08}": out += "\\b"
            case "\u{0C}": out += "\\f"
            case "\n": out += "\\n"
            case "\r": out += "\\r"
            case "\t": out += "\\t"
            case _ where scalar.value < 0x20:
                let hex = String(scalar.value, radix: 16)
                out += "\\u" + String(repeating: "0", count: 4 - hex.count) + hex
            default:
                out.unicodeScalars.append(scalar)
            }
        }
        return out + "\""
    }
}
