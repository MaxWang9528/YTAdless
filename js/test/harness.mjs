/**
 * Asserts that a posted message has the shape of TestVectors/bridge/<type>.json: no unknown
 * fields, every required field present, field types as in the sample `body`, finite numbers,
 * `enums` and `integers` respected, null only for `optional` fields.
 */
export function assertMatchesVector(message, label = '') {
  const where = label ? ` (${label})` : '';
  assert.ok(message && typeof message === 'object', `message is an object${where}`);
  const type = message.type;
  assert.equal(typeof type, 'string', `message has a type${where}`);
  const vector = bridgeVector(type);
  const { body, optional = [], enums = {}, integers = [] } = vector;
  assert.equal(message.v, 1, `${type}: v is 1${where}`);
  assert.ok(message.frame === 'main' || message.frame === 'sub', `${type}: frame is main|sub${where}`);
  for (const key of Object.keys(message)) {
    assert.ok(Object.hasOwn(body, key), `${type}: unexpected field "${key}"${where}`);
  }
  for (const [key, sample] of Object.entries(body)) {
    const isOptional = optional.includes(key);
    if (!Object.hasOwn(message, key) || message[key] === undefined) {
      assert.ok(isOptional, `${type}: missing required field "${key}"${where}`);
      continue;
    }
    const value = message[key];
    if (value === null) {
      assert.ok(isOptional, `${type}: "${key}" is null but not optional${where}`);
      continue;
    }
    assert.equal(typeof value, typeof sample, `${type}: "${key}" is a ${typeof sample}${where}`);
    if (typeof value === 'number') assert.ok(Number.isFinite(value), `${type}: "${key}" is finite${where}`);
    if (integers.includes(key)) assert.ok(Number.isInteger(value), `${type}: "${key}" is an integer${where}`);
    if (enums[key]) assert.ok(enums[key].includes(value), `${type}: "${key}"=${JSON.stringify(value)} is one of ${enums[key].join('|')}${where}`);
  }
}

// ── Network fakes ────────────────────────────────────────────────────────────────────────────
//
// A route: { match: string (substring) | RegExp | (url, {method}) => bool, method?, status = 200,
//            statusText?, headers = {}, body: string | object (sent as JSON text) | null,
//            delayMs = 0, times = Infinity }
// The first matching route answers. Bodies always reach the page as text, so the page parses
// them in its own realm, as on device.

function normalizeRoute(route) {
  assert.ok(route && route.match !== undefined, 'route needs a `match`');
  const body = route.body == null ? '' : typeof route.body === 'string' ? route.body : JSON.stringify(route.body);
  return {
    match: route.match,
    method: route.method ? route.method.toUpperCase() : null,
    status: route.status ?? 200,
    statusText: route.statusText ?? (route.status && route.status !== 200 ? '' : 'OK'),
    headers: { 'content-type': typeof route.body === 'object' && route.body !== null ? 'application/json' : 'text/plain', ...(route.headers || {}) },
    body,
    delayMs: route.delayMs ?? 0,
    remaining: route.times ?? Infinity,
  };
}

function routeMatches(route, url, method) {
  if (route.remaining <= 0) return false;
  if (route.method && route.method !== method) return false;
  if (typeof route.match === 'string') return url.includes(route.match);
  if (route.match instanceof RegExp) return route.match.test(url);
  if (typeof route.match === 'function') return Boolean(route.match(url, { method }));
  return false;
}

function installNetworkFakes(win, page) {
  const pageJSONParse = win.JSON.parse;  // the page's pristine parse, like Response.json() on device
  const NodeResponse = globalThis.Response;

  class Response extends NodeResponse {
    async json() { return pageJSONParse(await this.text()); }
    clone() {
      const copy = super.clone();
      Object.setPrototypeOf(copy, Response.prototype);
      if (Object.hasOwn(this, 'url')) Object.defineProperty(copy, 'url', { value: this.url, configurable: true });
      return copy;
    }
  }

  function findRoute(url, method) {
    const route = page.routes.find((r) => routeMatches(r, url, method));
    if (route) route.remaining -= 1;
    return route || null;
  }

  function delay(ms) {
    return new Promise((resolve) => win.setTimeout(resolve, ms));
  }

  async function fetch(input, init = {}) {
    const rawURL = typeof input === 'string' ? input : input && typeof input.url === 'string' ? input.url : String(input);
    const url = new URL(rawURL, win.location.href).href;
    const method = String(init.method || (input && input.method) || 'GET').toUpperCase();
    const body = init.body ?? null;
    page.requests.push({ api: 'fetch', method, url, body: body == null ? null : String(body) });
    const route = findRoute(url, method);
    if (route && route.delayMs) await delay(route.delayMs);
    if (!route) {
      page.unmatched.push({ api: 'fetch', method, url });
      throw new win.TypeError(`fakeFetch: no route for ${method} ${url}`);
    }
    const response = new Response(route.body, { status: route.status, statusText: route.statusText, headers: route.headers });
    Object.defineProperty(response, 'url', { value: url, configurable: true });
    return response;
  }

  win.fetch = fetch;
  win.Response = Response;
  win.Request = globalThis.Request;
  win.Headers = globalThis.Headers;
  win.XMLHttpRequest = makeFakeXHR(win, page, findRoute, pageJSONParse);
}

function makeFakeXHR(win, page, findRoute, pageJSONParse) {
  const UNSENT = 0, OPENED = 1, HEADERS_RECEIVED = 2, LOADING = 3, DONE = 4;
  const HANDLER_EVENTS = ['readystatechange', 'loadstart', 'progress', 'load', 'loadend', 'error', 'abort', 'timeout'];
  const states = new WeakMap();
  const st = (xhr) => states.get(xhr);

  function fire(xhr, type) {
    const event = new win.Event(type);
    xhr.dispatchEvent(event);
    const handler = st(xhr).handlers[type];
    if (typeof handler === 'function') {
      try {
        handler.call(xhr, event);
      } catch (error) {
        page.pageErrors.push({ source: `XMLHttpRequest.on${type}`, error });
      }
    }
  }

  class XMLHttpRequest extends win.EventTarget {
    constructor() {
      super();
      states.set(this, {
        readyState: UNSENT, method: 'GET', url: '', requestHeaders: {}, status: 0, statusText: '',
        responseHeaders: {}, text: '', responseURL: '', responseType: '', withCredentials: false,
        timeout: 0, handlers: {}, sent: false, aborted: false,
      });
    }

    get readyState() { return st(this).readyState; }
    get status() { return st(this).status; }
    get statusText() { return st(this).statusText; }
    get responseURL() { return st(this).responseURL; }
    get responseType() { return st(this).responseType; }
    set responseType(value) { st(this).responseType = String(value); }
    get withCredentials() { return st(this).withCredentials; }
    set withCredentials(value) { st(this).withCredentials = Boolean(value); }
    get timeout() { return st(this).timeout; }
    set timeout(value) { st(this).timeout = Number(value) || 0; }
    get upload() { return st(this).upload || (st(this).upload = new win.EventTarget()); }

    get responseText() {
      const s = st(this);
      return s.readyState >= LOADING ? s.text : '';
    }

    get response() {
      const s = st(this);
      if (s.responseType === '' || s.responseType === 'text') return s.readyState >= LOADING ? s.text : '';
      if (s.readyState !== DONE) return null;
      if (s.responseType === 'json') {
        try { return pageJSONParse(s.text); } catch (_) { return null; }
      }
      if (s.responseType === 'arraybuffer') return new win.TextEncoder().encode(s.text).buffer;
      return null;
    }

    open(method, url) {
      const s = st(this);
      s.method = String(method).toUpperCase();
      s.url = new URL(String(url), win.location.href).href;
      s.readyState = OPENED;
      s.sent = false;
      s.aborted = false;
      s.status = 0;
      s.text = '';
      fire(this, 'readystatechange');
    }

    setRequestHeader(name, value) {
      st(this).requestHeaders[String(name).toLowerCase()] = String(value);
    }

    getResponseHeader(name) {
      const value = st(this).responseHeaders[String(name).toLowerCase()];
      return value === undefined ? null : value;
    }

    getAllResponseHeaders() {
      return Object.entries(st(this).responseHeaders).map(([k, v]) => `${k}: ${v}\r\n`).join('');
    }

    overrideMimeType() {}

    abort() {
      const s = st(this);
      if (!s.sent || s.readyState === DONE) return;
      s.aborted = true;
      s.readyState = DONE;
      s.status = 0;
      fire(this, 'readystatechange');
      fire(this, 'abort');
      fire(this, 'loadend');
      s.readyState = UNSENT;
    }

    send(body = null) {
      const s = st(this);
      if (s.readyState !== OPENED || s.sent) throw new win.DOMException('send() needs open()', 'InvalidStateError');
      s.sent = true;
      page.requests.push({ api: 'xhr', method: s.method, url: s.url, body: body == null ? null : String(body), headers: { ...s.requestHeaders } });
      const route = findRoute(s.url, s.method);
      fire(this, 'loadstart');
      win.setTimeout(() => {
        if (s.aborted) return;
        if (!route) {
          page.unmatched.push({ api: 'xhr', method: s.method, url: s.url });
          s.readyState = DONE;
          fire(this, 'readystatechange');
          fire(this, 'error');
          fire(this, 'loadend');
          return;
        }
        s.status = route.status;
        s.statusText = route.statusText;
        s.responseURL = s.url;
        s.responseHeaders = Object.fromEntries(Object.entries(route.headers).map(([k, v]) => [k.toLowerCase(), String(v)]));
        s.readyState = HEADERS_RECEIVED;
        fire(this, 'readystatechange');
        s.text = route.body;
        s.readyState = LOADING;
        fire(this, 'readystatechange');
        fire(this, 'progress');
        s.readyState = DONE;
        fire(this, 'readystatechange');
        fire(this, 'load');
        fire(this, 'loadend');
      }, route ? route.delayMs : 0);
    }
  }

  for (const type of HANDLER_EVENTS) {
    Object.defineProperty(XMLHttpRequest.prototype, `on${type}`, {
      configurable: true,
      enumerable: true,
      get() { return st(this).handlers[type] ?? null; },
      set(fn) { st(this).handlers[type] = typeof fn === 'function' ? fn : null; },
    });
  }
  for (const [name, value] of Object.entries({ UNSENT, OPENED, HEADERS_RECEIVED, LOADING, DONE })) {
    Object.defineProperty(XMLHttpRequest, name, { value });
    Object.defineProperty(XMLHttpRequest.prototype, name, { value });
  }
  return XMLHttpRequest;
}

// ── The page ─────────────────────────────────────────────────────────────────────────────────

/**
 * @param {object} [options]
 * @param {'browse'|'player'} [options.role='browse']
 * @param {string} [options.url='https://m.youtube.com/'] page URL (the parent's URL for frame 'sub')
 * @param {string|null} [options.html] page HTML placed after the start scripts
 * @param {boolean} [options.runInlineScripts=true] run the HTML's inline <script>s
 * @param {'main'|'sub'} [options.frame='main'] 'sub' = an about:blank iframe of a main page
 * @param {'all'|'none'|string[]} [options.scripts='all'] manifest files to inject
 * @param {boolean} [options.debug=false] @param {string} [options.build='test'] prelude config
 * @param {object[]} [options.routes] fetch/XHR routes (see above); add more with page.route()
 * @param {boolean} [options.webkit=true] install the fake message handler
 * @param {(window, page) => void} [options.beforeScripts] install mocks before any script runs
 * @param {'start'|'complete'} [options.until='complete']
 * @param {boolean} [options.forwardConsole] print page console output (env YTADLESS_CONSOLE=1)
 */
export async function createPage(options = {}) {
  const {
    role = 'browse',
    url = 'https://m.youtube.com/',
    html = null,
    runInlineScripts = true,
    frame = 'main',
    scripts = 'all',
    debug = false,
    build = 'test',
    routes = [],
    webkit = true,
    beforeScripts = null,
    until = 'complete',
    forwardConsole = process.env.YTADLESS_CONSOLE === '1',
  } = options;
  assert.ok(role === 'browse' || role === 'player', `role must be browse|player, got ${role}`);
  assert.ok(frame === 'main' || frame === 'sub', `frame must be main|sub, got ${frame}`);

  const page = {
    role,
    frame,
    messages: [],
    requests: [],
    unmatched: [],
    routes: [],
    loaded: [],
    console: [],
    jsdomErrors: [],
    pageErrors: [],
    readyState: 'loading',
  };

  const virtualConsole = new VirtualConsole();
  for (const level of ['log', 'info', 'warn', 'error', 'debug']) {
    virtualConsole.on(level, (...args) => {
      page.console.push({ level, args });
      if (forwardConsole) console[level]('[page]', ...args);
    });
  }
  virtualConsole.on('jsdomError', (error) => {
    page.jsdomErrors.push(error);
    if (error.type === 'unhandled-exception') page.pageErrors.push({ source: 'uncaught', error: error.detail ?? error });
    if (forwardConsole) console.error('[jsdom]', error.message);
  });

  const dom = new JSDOM('<!doctype html>' + DEFAULT_HTML, {
    url,
    runScripts: 'outside-only',
    pretendToBeVisual: true,
    virtualConsole,
  });
  // jsdom fires its own DOMContentLoaded/load asynchronously; let them pass before emulating.
  await new Promise((resolve) => {
    if (dom.window.document.readyState === 'complete') resolve();
    else dom.window.addEventListener('load', () => resolve(), { once: true });
  });

  let win = dom.window;
  if (frame === 'sub') {
    const iframe = dom.window.document.createElement('iframe');
    dom.window.document.body.appendChild(iframe);
    win = iframe.contentWindow;
  }
  const doc = win.document;
  page.dom = dom;
  page.window = win;
  page.document = doc;

  // Document start: only <html>, no <head>/<body>.
  doc.documentElement.replaceChildren();
  Object.defineProperty(doc, 'readyState', { configurable: true, get: () => page.readyState });
  try {
    Object.defineProperty(win.navigator, 'userAgent', { configurable: true, get: () => IPHONE_SAFARI_UA });
  } catch (_) { /* keep jsdom's */ }

  if (webkit) {
    const handler = {
      postMessage(body) {
        page.messages.push(structuredClone(body));  // throws DataCloneError like WebKit
      },
    };
    win.webkit = { messageHandlers: { [HANDLER]: handler } };
  }
  installNetworkFakes(win, page);

  const runSource = (source, filename) => {
    try {
      return new vm.Script(source, { filename }).runInContext(win);
    } catch (error) {
      page.pageErrors.push({ source: filename, error });
      return undefined;
    }
  };

  const plan = scripts === 'none' ? [] : injectionPlan({ role, debug, build, frame, only: Array.isArray(scripts) ? scripts : null });
  const inject = (injection) => {
    for (const script of plan) {
      if (script.injection !== injection) continue;
      runSource(script.source, `ytadless/${script.name}`);
      page.loaded.push(script.name);
    }
  };

  Object.assign(page, {
    /** Adds fetch/XHR routes. */
    route(...more) {
      for (const r of more.flat()) page.routes.push(normalizeRoute(r));
      return page;
    },
    fakeFetch(more) {
      return page.route(more);
    },
    /** Runs a classic script in the page, like an inline <script>. Throws what it throws. */
    runInline(source, filename = 'inline.js') {
      return new vm.Script(source, { filename }).runInContext(win);
    },
    /** Places `markup` (a full document or a fragment) into the document; runs its inline scripts. */
    setHTML(markup, { runInlineScripts: run = true } = {}) {
      const parsed = new win.DOMParser().parseFromString(markup, 'text/html');
      for (const attr of [...parsed.documentElement.attributes]) doc.documentElement.setAttribute(attr.name, attr.value);
      const sources = run
        ? [...parsed.querySelectorAll('script')]
          .filter((s) => !s.hasAttribute('src') && CLASSIC_SCRIPT_TYPE.test((s.getAttribute('type') || '').trim()))
          .map((s) => s.textContent)
        : [];
      doc.documentElement.replaceChildren(...[...parsed.documentElement.childNodes].map((n) => doc.adoptNode(n)));
      sources.forEach((source, i) => runSource(source, `inline-${i}.js`));
    },
    /** Steps 5–7 of the lifecycle (called by createPage unless `until: 'start'`). */
    finishLoading({ html: markup = html, runInlineScripts: run = runInlineScripts } = {}) {
      page.setHTML(markup ?? DEFAULT_HTML, { runInlineScripts: run });
      page.readyState = 'interactive';
      doc.dispatchEvent(new win.Event('readystatechange'));
      doc.dispatchEvent(new win.Event('DOMContentLoaded', { bubbles: true }));
      inject('end');
      page.readyState = 'complete';
      doc.dispatchEvent(new win.Event('readystatechange'));
      win.dispatchEvent(new win.Event('load'));
      return page;
    },
    /** Like native `send`: calls __ytadless.cmd(name, JSON args), awaits, returns a Node-realm copy. */
    async cmd(name, args = {}) {
      const ns = win[NAMESPACE];
      if (!ns) return { error: 'no-bridge' };
      const result = await ns.cmd(name, JSON.stringify(args));
      return result === undefined || result === null ? null : JSON.parse(JSON.stringify(result));
    },
    posted(type) {
      return type === undefined ? page.messages : page.messages.filter((m) => m.type === type);
    },
    scriptErrors() {
      return page.posted('scriptError');
    },
    /** Waits for pending page timers (and the microtasks before them). */
    flush(ms = 0) {
      return new Promise((resolve) => win.setTimeout(resolve, ms));
    },
    close() {
      dom.window.close();
    },
  });

  page.route(routes);
  if (typeof beforeScripts === 'function') beforeScripts(win, page);
  inject('start');
  if (until !== 'start') page.finishLoading();
  return page;
}

/**
 * Injects a role's manifest scripts into a page made with `scripts: 'none'`, for tests that
 * need to act between page creation and injection. Throws whatever a script throws.
 */
export function loadManifestScripts(page, { injection = 'start', debug = false, build = 'test', only = null } = {}) {
  const plan = injectionPlan({ role: page.role, debug, build, frame: page.frame, only });
  const names = [];
  for (const script of plan) {
    if (script.injection !== injection) continue;
    page.runInline(script.source, `ytadless/${script.name}`);
    page.loaded.push(script.name);
    names.push(script.name);
  }
  return names;
}

/** Asserts the page posted no scriptError and nothing threw into it. */
export function assertClean(page, label = '') {
  const where = label ? ` (${label})` : '';
  assert.deepEqual(page.scriptErrors(), [], `no scriptError${where}`);
  assert.deepEqual(page.pageErrors.map((e) => `${e.source}: ${e.error && e.error.message}`), [], `nothing threw into the page${where}`);
}
