// harness.mjs — a simulated m.youtube.com page for the injected-script tests (PLAN.md §5.7, §7).
// Owner: P0 (frozen). Build module-specific helpers in your own test files, or install them
// through the `beforeScripts` hook, rather than editing this file.
//
// createPage() mirrors what WebKit does on device, in this order:
//   1. a document with only <html> (no <head>/<body>), readyState 'loading'  ← document start
//   2. fakes: webkit.messageHandlers.ytadless, fetch/Response/Request/Headers, XMLHttpRequest
//   3. options.beforeScripts(window, page)
//   4. the manifest's `start` scripts for the role, prelude first (same plan as Swift's
//      ScriptManifest.injectionPlan; frame 'sub' skips mainFrameOnly scripts)
//   5. the page HTML, then its inline <script>s in document order (DOM placed first, then run)
//   6. readyState 'interactive', DOMContentLoaded, then the `end` scripts
//   7. readyState 'complete', window 'load'
// Pass `until: 'start'` to stop after step 4 and call `page.finishLoading()` yourself.

